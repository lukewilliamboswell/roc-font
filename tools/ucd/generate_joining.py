"""Generate the shaper's joining properties from pinned Unicode 18 data.

These are shaping properties, not segmentation tables. Joining type and
the two Syriac groups are the inputs of HarfBuzz's Arabic joining machine.
The generated pool contains disjoint scalar ranges; non-joining is implicit.
"""
from pathlib import Path
import argparse
import hashlib
import json
from urllib.request import urlopen

HERE = Path(__file__).resolve().parent
OUTPUT = HERE.parents[1] / 'package' / 'ShaperJoiningData.roc'


def fetch(name, pin):
    cache = HERE / '.cache' / name
    if not cache.exists():
        cache.parent.mkdir(exist_ok=True)
        cache.write_bytes(urlopen(pin['url']).read())
    data = cache.read_bytes()
    if len(data) != pin['size'] or hashlib.sha256(data).hexdigest() != pin['sha256']:
        raise ValueError('joining data does not match pin: ' + name)
    return data.decode('utf8')


def rows(text):
    for line in text.splitlines():
        line = line.split('#', 1)[0].strip()
        if line:
            yield [field.strip() for field in line.split(';')]


def generate():
    pins = json.loads((HERE / 'joining-pins.json').read_text())
    files = {name: fetch(name, pin) for name, pin in pins['files'].items()}
    values = [0] * 0x110000
    types = {'U': 0, 'L': 1, 'R': 2, 'D': 3, 'C': 3, 'T': 6}
    for fields in rows(files['DerivedJoiningType.txt']):
        bounds = fields[0].split('..')
        first, last = int(bounds[0], 16), int(bounds[-1], 16)
        values[first:last + 1] = [types[fields[1]]] * (last - first + 1)
    for fields in rows(files['ArabicShaping.txt']):
        if fields[3] in ('ALAPH', 'DALATH RISH'):
            values[int(fields[0], 16)] = 4 if fields[3] == 'ALAPH' else 5
    ranges = []
    start = 0
    for i in range(1, len(values) + 1):
        if i == len(values) or values[i] != values[start]:
            if values[start]:
                ranges.append((start, i - 1, values[start]))
            start = i
    notice = ['# ' + line if line else '#' for line in (HERE / 'UNICODE-LICENSE.txt').read_text().splitlines()]
    out = notice + ['','## Unicode 18.0.0 joining properties generated by generate_joining.py.',
           '## Inputs are pinned in tools/ucd/joining-pins.json. Do not edit.',
           'ShaperJoiningData :: {}.{',
           '\tranges : List({ first : U32, last : U32, kind : U8 })',
           '\tranges = [']
    out.extend(f'\t\t{{ first: {first}, last: {last}, kind: {kind} }},' for first, last, kind in ranges)
    out.extend(['\t]', '}'])
    return '\n'.join(out) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    expected = generate()
    if args.check:
        if OUTPUT.read_text() != expected:
            raise SystemExit('ShaperJoiningData.roc differs; regenerate joining data')
    else:
        OUTPUT.write_text(expected)


if __name__ == '__main__':
    main()
