#!/usr/bin/env python3
"""Generate the Unicode property table for modern Devanagari shaping."""

import argparse
import json

from generate import HERE, ROOT, code_range, fetch, lines

PINS = HERE / "indic-pins.json"
OUTPUT = ROOT / "package" / "ShaperIndicData.roc"
FIRST = 0x0900
END = 0x0980
EXTRA = (0x00A0, 0x200C, 0x200D, 0x25CC)
SYLLABIC = [
    "Other", "Consonant", "Vowel_Independent", "Vowel_Dependent", "Virama",
    "Nukta", "Bindu", "Visarga", "Avagraha", "Cantillation_Mark",
    "Consonant_Placeholder", "Joiner", "Non_Joiner", "Number",
]
POSITIONAL = ["NA", "Left", "Right", "Top", "Bottom"]


def properties(data: bytes, values: list[str]) -> dict[int, int]:
    selected = {}
    for span, kind in lines(data):
        first, last = code_range(span)
        for cp in range(max(FIRST, first), min(END, last + 1)):
            selected[cp] = values.index(kind)
        for cp in EXTRA:
            if first <= cp <= last:
                selected[cp] = values.index(kind)
    return selected


def build() -> str:
    pins = json.loads(PINS.read_text())
    syllabic_file = "IndicSyllabicCategory.txt"
    positional_file = "IndicPositionalCategory.txt"
    syllabic = properties(fetch(syllabic_file, pins["files"][syllabic_file]), SYLLABIC)
    positional = properties(fetch(positional_file, pins["files"][positional_file]), POSITIONAL)

    def packed(cp):
        return syllabic.get(cp, 0) + 16 * positional.get(cp, 0)

    out = [
        f"## Unicode {pins['unicode']} Indic properties for the Devanagari block.",
        "## Generated by `tools/ucd/generate_indic.py` from `indic-pins.json`.",
        "## The low four bits hold the syllabic category, the high four its position.",
        "ShaperIndicData :: {}.{",
        "",
        "\tproperties : U32 -> U8",
        "\tproperties = |cp|",
        f"\t\tif cp >= 0x{FIRST:04X} and cp < 0x{END:04X} {{",
        f"\t\t\tShaperIndicData.devanagari.get((cp - 0x{FIRST:04X}).to_u64()) ?? 0",
        "\t\t} else {",
        "\t\t\tmatch cp {",
        *(f"\t\t\t\t0x{cp:04X} => {packed(cp)}" for cp in EXTRA),
        "\t\t\t\t_ => 0",
        "\t\t\t}",
        "\t\t}",
        "",
        "\tdevanagari : List(U8)",
        "\tdevanagari = [",
    ]
    out.extend(f"\t\t{packed(cp)}," for cp in range(FIRST, END))
    out.extend(["\t]", ""])
    for prefix, values in (("syllabic", SYLLABIC), ("positional", POSITIONAL)):
        for value, name in enumerate(values):
            identifier = f"{prefix}_{name.lower()}"
            out.extend([f"\t{identifier} : U8", f"\t{identifier} = {value}", ""])
    out[-1] = "}"
    return "\n".join(out) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = build()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text() != generated:
            parser.exit(1, f"{OUTPUT.relative_to(ROOT)} differs from the pinned Unicode table\n")
    else:
        OUTPUT.write_text(generated)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
