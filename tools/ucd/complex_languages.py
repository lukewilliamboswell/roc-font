#!/usr/bin/env python3
"""Write the multi-subtag language table of package/ShaperLanguages.roc from
HarfBuzz's `hb_ot_tags_from_complex_language` (src/hb-ot-tag-table.hh of the
pinned HarfBuzz release in the corpus, tests/corpus/harfbuzz-14.6.0/).

HarfBuzz maps some BCP 47 tags by more than their primary subtag: a region
(`zh-HK` is ZHH, `zh-TW` ZHT), a script (`zh-Hant`), or a variant
(`el-polyton` is PGR). The function is a generated chain of string tests;
each test becomes one rule here, in HarfBuzz's order:

  kind 0  a variant after the first subtag: `subtag_matches (p, limit, b)`
          where p is the first '-' (tags of at least 7 characters)
  kind 1  the whole tag equals `first` + `a` (`strcmp`)
  kind 2  the tag after `first` starts with `a`, then ends or has a '-'
          (`lang_matches`)
  kind 3  the tag after `first` starts with `a` and has the subtag `b`
          (`strncmp` and `subtag_matches`)

Usage:
  python3 tools/ucd/complex_languages.py           # rewrite the table
  python3 tools/ucd/complex_languages.py --check   # fail if it differs
"""

from __future__ import annotations

import argparse
import re
import sys
import tarfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
TARBALL = ROOT / "tests" / "corpus" / "harfbuzz-14.6.0" / "harfbuzz-14.6.0.tar.xz"
MEMBER = "harfbuzz-14.6.0/src/hb-ot-tag-table.hh"
TARGET = ROOT / "package" / "ShaperLanguages.roc"
BEGIN = "\t## Language tags HarfBuzz maps by more than their primary subtag"
END = "\t# End of the generated complex table."


def source() -> str:
    with tarfile.open(TARBALL) as tar:
        member = tar.extractfile(MEMBER)
        if member is None:
            sys.exit(f"{MEMBER} not in {TARBALL}")
        return member.read().decode("utf-8")


def rules(text: str) -> list[tuple[str, int, str, str, list[str]]]:
    start = text.index("hb_ot_tags_from_complex_language (const char")
    body = text[start:text.index("\n}\n", start)]
    out = []
    first = ""
    pending: tuple[int, str, str] | None = None
    tags: list[str] = []
    for raw in body.splitlines():
        line = raw.strip()
        if m := re.match(r"case '(.)':", line):
            first = m.group(1)
        elif m := re.match(r'if \(subtag_matches \(p, limit, "([^"]+)", \d+\)\)', line):
            pending = (0, "", m.group(1))
        elif m := re.match(r'if \(0 == strcmp \(&lang_str\[1\], "([^"]+)"\)\)', line):
            pending = (1, m.group(1), "")
        elif m := re.match(r'if \(lang_matches \(&lang_str\[1\], limit, "([^"]+)", (\d+)\)\)', line):
            assert len(m.group(1)) == int(m.group(2))
            pending = (2, m.group(1), "")
        elif m := re.match(r'if \(0 == strncmp \(&lang_str\[1\], "([^"]+)", (\d+)\)', line):
            assert len(m.group(1)) == int(m.group(2))
            pending = (3, m.group(1), "")
        elif m := re.match(r'&& subtag_matches \(lang_str, limit, "([^"]+)", (\d+)\)\)', line):
            assert pending and pending[0] == 3
            pending = (3, pending[1], m.group(1))
        elif m := re.match(r"(?:tags\[0\] = )?HB_TAG\('(.)','(.)','(.)','(.)'\)", line):
            tags.append("".join(m.groups()))
        elif line.startswith("return true;"):
            assert pending is not None and tags, line
            kind, a, b = pending
            out.append(("" if kind == 0 else first, kind, a, b, tags))
            pending, tags = None, []
    return out


def table(found) -> str:
    lines = [
        BEGIN,
        "\t## (HarfBuzz's `hb_ot_tags_from_complex_language`, generated by",
        "\t## `tools/ucd/complex_languages.py`; see it for the rule kinds), in",
        "\t## HarfBuzz's order: the first rule that matches gives the tags.",
        "\tcomplex : List({ first : Str, kind : U8, a : Str, b : Str, tags : Str })",
        "\tcomplex = [",
    ]
    for first, kind, a, b, tags in found:
        lines.append(f'\t\t{{ first: "{first}", kind: {kind}, a: "{a}", b: "{b}", tags: "{"".join(tags)}" }},')
    lines.append("\t]")
    lines.append(END)
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = table(rules(source()))
    text = TARGET.read_text()
    if BEGIN in text:
        current = text[text.index(BEGIN):text.index(END) + len(END)]
    else:
        current = None
    if args.check:
        if current != generated:
            print("ShaperLanguages.roc's complex table is not what tools/ucd/complex_languages.py writes", file=sys.stderr)
            return 1
        print("ShaperLanguages.roc's complex table is up to date")
        return 0
    if current is None:
        cut = text.rindex("\n}")
        text = text[:cut] + "\n\n" + generated + text[cut:]
    else:
        text = text.replace(current, generated)
    TARGET.write_text(text)
    print(f"wrote {len(rules(source()))} rules")
    return 0


if __name__ == "__main__":
    sys.exit(main())
