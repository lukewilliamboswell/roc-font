#!/usr/bin/env python3
"""Generate the Arabic joining table from the pinned Unicode UCD.

A row stores two inclusive 21-bit bounds and a three-bit joining type.
Join-causing characters have both joining directions, like dual-joining
characters. Unlisted scalars are non-joining.
"""
import argparse
import json

from generate import HERE, ROOT, code_range, fetch, lines

PINS = HERE / "arabic-pins.json"
OUTPUT = ROOT / "package" / "ShaperArabicData.roc"
TYPES = {"L": 1, "R": 2, "D": 3, "C": 3, "T": 4}


def generate() -> str:
    pins = json.loads(PINS.read_text())
    name = "DerivedJoiningType.txt"
    data = fetch(name, pins["files"][name])
    ranges: list[tuple[int, int, int]] = []
    for block, category in lines(data):
        lo, hi = code_range(block)
        if category in TYPES:
            ranges.append((lo, hi, TYPES[category]))

    merged: list[tuple[int, int, int]] = []
    for lo, hi, kind in sorted(ranges):
        if merged:
            start, last, previous = merged[-1]
            if lo <= last:
                raise ValueError(f"overlapping joining ranges at {lo:#x}")
            if lo == last + 1 and previous == kind:
                merged[-1] = start, hi, kind
                continue
        merged.append((lo, hi, kind))

    words = [f"0x{(lo << 24) | (hi << 3) | kind:012X}" for lo, hi, kind in merged]
    out = [
        f"## Joining types from Unicode {pins['unicode']} DerivedJoiningType.txt.",
        "## Generated by tools/ucd/generate_arabic.py from arabic-pins.json.",
        "ShaperArabicData :: {}.{",
        "\tranges : List(U64)",
        "\tranges = [",
    ]
    out.extend("\t\t" + word + "," for word in words)
    out.extend(["\t]", "}"])
    return "\n".join(out) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    actual = generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != actual:
            raise SystemExit(f"{OUTPUT.name} differs from the pinned joining data")
    else:
        OUTPUT.write_text(actual)


if __name__ == "__main__":
    main()
