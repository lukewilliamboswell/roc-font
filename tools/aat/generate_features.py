"""Emit pinned declarative OpenType-to-Apple feature mappings, offline."""
import argparse,json
from pathlib import Path
HERE=Path(__file__).resolve().parent
parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
d=json.loads((HERE/'feature-map.json').read_text())
rows=[]
for e in d['entries']:
 assert len(e['tag'].encode('ascii'))==4
 tag=int.from_bytes(e['tag'].encode('ascii'),'big')
 rows.append(f'\t\t{{ tag: {tag}, type: {e["type"]}, on: {e["on"]}, off: {e["off"]} }},')
text=(HERE/'NOTICE.txt').read_text()+'''\n## Pinned HarfBuzz 14.6.0 declarative feature mapping. Internal.
## Generated by tools/aat/generate_features.py; do not edit by hand.
AatFeatureData :: {}.{
	Mapping : { tag : U64, type : U64, on : U64, off : U64 }
	mappings : List(Mapping)
	mappings = [
'''+ '\n'.join(rows)+ '\n\t]\n}\n'
p=HERE.parents[1]/'package/AatFeatureData.roc'
if args.check:assert p.read_text()==text,f'stale {p}'
else:p.write_text(text)
