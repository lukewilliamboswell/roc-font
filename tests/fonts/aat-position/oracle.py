HERE=Path(__file__).resolve().parent

def shape(path,text,direction,kern=True,weight=0):
 f=hb.Font(hb.Face(path.read_bytes()));f.scale=(f.face.upem,f.face.upem);f.set_variations({'wght':weight})
 b=hb.Buffer();b.add_utf8(text.encode());b.direction=direction;b.script='Latn';b.language='en';hb.shape(f,b,{'kern':int(kern),'vkrn':int(kern)})
 return {'glyphs':[i.codepoint for i in(b.glyph_infos or [])],'clusters':[i.cluster for i in(b.glyph_infos or [])],'advances':[[p.x_advance,p.y_advance]for p in(b.glyph_positions or [])],'offsets':[[p.x_offset,p.y_offset]for p in(b.glyph_positions or [])]}

def main():
 cases=[]
 texts=['','a','ab','ba','abc','abab','acbab','a\u0301b','ab\u0301c','a\u200db','a\u200cb']
 for path in sorted(HERE.glob('*.ttf')):
  if path.name=='kerx1-cycle.ttf':continue # Resource contract only, no fabricated partial-progress golden.
  selected=['AV','VA','Ta','To','Wa','AY','Hello']if path.name=='Jellee-Roman.ttf'else texts
  if path.name in ['kerx1.ttf','kerx1-reset.ttf','kerx1-epsilon.ttf','apple-kern1.ttf','ot-kern1.ttf']:selected=selected+['a'*n+'b'for n in [13,15,17]]
  if path.name.startswith('kerx4-point-wide'):selected=['ab','ba']
  if path.name=='kerx4-chain.ttf':selected=selected+['a'*n for n in [64,65,66,257]]
  for text in selected:
   for direction in (['ltr','rtl']if path.name.startswith('kerx4-point-wide')else['ltr','rtl','ttb','btt']):
    for kern in ([True]if path.name.startswith('kerx4-point-wide')else[True,False]):
     weights=[0,1]if'tuple'in path.name or 'variable'in path.name else[1]if'wide'in path.name else[0]
     for weight in weights:
      cases.append({'id':f'aatpos-{len(cases)}','font':path.name,'font_sha256':hashlib.sha256(path.read_bytes()).hexdigest(),'text':text,'direction':direction,'kern':kern,'weight':weight,'oracle':shape(path,text,direction,kern,weight)})
 for c in cases:
  if c['font'].startswith('kerx4-point-wide'):
   c['oracle_ot_font_funcs']=c['oracle']
   c['oracle_freetype_2_13_2']=shape_points(HERE/c['font'],c['text'],c['direction'],c['kern'],c['weight'])
   c['oracle']=shape_points(HERE/c['font'],c['text'],c['direction'],c['kern'],c['weight'],source='fonttools')
   c['provenance']='HB14.6 with fontTools4.61.1 direct numeric gvar point materialization, IEEEbinary32 round-half-up then I32 wrap; not HB+FreeType parity'
   points=materialized_points(HERE/c['font'],1,c['weight'])
   c['fonttools_point2']={'raw':points[2],'binary32':[f32(v)for v in points[2]],'i32_wrapped':[point_conversion(v)for v in points[2]]}
  elif c['font'].startswith('kerx4-point'):
   c['oracle_ot_font_funcs']=c['oracle']
   c['oracle']=shape_points(HERE/c['font'],c['text'],c['direction'],c['kern'],c['weight'])
   c['provenance']='HB14.6 OT functions plus explicit unhinted FreeType2.13.2 contour-point callback'
 out={'oracles':{'uharfbuzz':hb.__version__,'harfbuzz':hb.version_string(),'fontTools':fontTools.__version__,'FreeType':'.'.join(map(str,freetype.version())),'contour_points':'FreeType2.13.2 unhinted/no-scale callback'},'cases':cases}
 (HERE/'cases.jsonc').write_text('// Actual pinned HB reference results, generated by oracle.py.\n'+json.dumps(out,ensure_ascii=False,indent=2)+'\n')
 print(f'Recorded {len(cases)} actual native reference cases; point callback provenance is explicit per case.')
 for name in ['kerx0','kerx1','kerx1-tuple','kerx4-coordinate','kerx4-point','kerx4-anchor','apple-kern1']:
  example=next(c for c in cases if c['font']==name+'.ttf' and c['text']=='ab' and c['direction']=='ltr' and c['kern']);print(name,example['oracle'])
if __name__=='__main__':main()
