"""Print tables of a committed test font as Roc byte lists, for in-package
expects that test internal readers on real fixture bytes.

A package module must not import a file under `tests/` (that would put the
test font into `roc bundle`), so expects inside `package/*.roc` that need a
fixture's tables embed them, generated by this script:

    python3 -I tests/fonts/inline_tables.py FONT NAME=TAG [NAME=TAG ...]

Each NAME=TAG prints `NAME : List(U8)` holding table TAG, 16 bytes a row.
Three pseudo tags print a `U64` instead: `maxp.numGlyphs`,
`head.indexToLocFormat` and `hhea.numberOfHMetrics`.

Example (the tables `package/TableVar.roc` embeds):

    python3 -I tests/fonts/inline_tables.py tests/fonts/variable/var-mapped.ttf \\
        mapped_fvar=fvar mapped_avar=avar mapped_hvar=HVAR
"""
import struct
import sys

FIELDS = {
    "maxp.numGlyphs": ("maxp", 4),
    "head.indexToLocFormat": ("head", 50),
    "hhea.numberOfHMetrics": ("hhea", 34),
}


def tables(data):
    count = struct.unpack(">H", data[4:6])[0]
    out = {}
    for i in range(count):
        tag, _, offset, length = struct.unpack(">4sIII", data[12 + 16 * i:28 + 16 * i])
        out[tag.decode("latin-1")] = data[offset:offset + length]
    return out


def main(argv):
    if len(argv) < 3:
        sys.exit(__doc__)
    path = argv[1]
    with open(path, "rb") as f:
        found = tables(f.read())
    print(f"# Generated from `{path}` by `tests/fonts/inline_tables.py`.")
    for arg in argv[2:]:
        name, tag = arg.split("=", 1)
        if tag in FIELDS:
            table, at = FIELDS[tag]
            value = struct.unpack(">H", found[table][at:at + 2])[0]
            print(f"\n{name} : U64\n{name} = {value}")
            continue
        data = found[tag]
        rows = [", ".join(f"0x{b:02X}" for b in data[k:k + 16]) for k in range(0, len(data), 16)]
        print(f"\n# The `{tag}` table, {len(data)} bytes.")
        print(f"{name} : List(U8)")
        print(f"{name} = [")
        for row in rows:
            print(f"\t[{row}],")
        print("].join_map(|row| row)")


if __name__ == "__main__":
    main(sys.argv)
